namespace UltimaMilla.Application;

public static class DependencyInjection
{
    /// <summary>Registra Handlers y Validators de Application.</summary>
    public static IServiceCollection AddApplication(this IServiceCollection services)
    {
        services.AddValidatorsFromAssemblyContaining<CrearEnvioValidator>();

        services.AddScoped<CrearEnvioHandler>();
        services.AddScoped<ImportarEnviosCsvHandler>();
        services.AddScoped<ListarEnviosHandler>();
        services.AddScoped<ObtenerDetalleEnvioHandler>();
        services.AddScoped<RegistrarEventoMovilHandler>();
        services.AddScoped<RecibirEnDepositoHandler>();
        services.AddScoped<ListarDiscrepanciasRecepcionHandler>();
        services.AddScoped<RetornarADepositoHandler>();
        services.AddScoped<SolicitarReprogramacionHandler>();
        services.AddScoped<ConfirmarReprogramacionHandler>();
        services.AddScoped<ListarSolicitudesReprogramacionHandler>();
        services.AddScoped<IniciarDevolucionHandler>();
        services.AddScoped<ConfirmarDevolucionHandler>();
        services.AddScoped<ListarCuentasComercialesHandler>();
        services.AddScoped<SolicitarVinculacionHandler>();
        services.AddScoped<AceptarVinculacionHandler>();
        services.AddScoped<RechazarVinculacionHandler>();
        services.AddScoped<ListarSolicitudesPendientesHandler>();
        services.AddScoped<ListarOperadoresHandler>();
        services.AddScoped<ActualizarTarifaHandler>();
        services.AddScoped<ObtenerTarifaVigenteHandler>();
        services.AddScoped<ActualizarReglasOperativasHandler>();
        services.AddScoped<ObtenerReglasOperativasVigentesHandler>();
        services.AddScoped<ListarZonasHandler>();
        services.AddScoped<ObtenerZonaHandler>();
        services.AddScoped<EditarZonaHandler>();
        services.AddScoped<CrearHojaDeRutaHandler>();
        services.AddScoped<ConsultarHojasDeRutaHandler>();
        services.AddScoped<DespacharHojaDeRutaHandler>();
        services.AddScoped<QuitarEnvioDeRutaHandler>();
        services.AddScoped<AgregarEnvioARutaHandler>();
        services.AddScoped<DeclararExtravioHandler>();
        services.AddScoped<RegistrarReaparicionHandler>();
        services.AddScoped<ObtenerMisHojasDeRutaHandler>();
        services.AddScoped<DespacharMiHojaDeRutaHandler>();
        services.AddScoped<RendirHojaDeRutaHandler>();
        services.AddScoped<RegistrarPosicionesHandler>();
        services.AddScoped<RegistrarDispositivoHandler>();
        services.AddScoped<EnviarNotificacionDePruebaHandler>();
        services.AddScoped<CrearRetiroHandler>();
        services.AddScoped<CrearTarifaHandler>();
        services.AddScoped<ConsultarRetirosHandler>();
        services.AddScoped<AgregarRetiroARutaHandler>();
        services.AddScoped<GestionarRetiroHandler>();
        services.AddScoped<RegistrarEventoRetiroHandler>();
        services.AddScoped<ObtenerResumenRetirosHandler>();
        services.AddScoped<RegistrarAvisosRetiroHandler>();

        // Avisos a comercios (RNF 6.9): RegistrarAvisos y EntregarAviso los invoca el Worker.
        services.AddScoped<RegistrarAvisosHandler>();
        services.AddScoped<EntregarAvisoHandler>();
        services.AddScoped<ReenviarAvisoHandler>();
        services.AddScoped<ReintentarAvisosFallidosHandler>();
        services.AddScoped<ListarMensajesFallidosHandler>();
        services.AddScoped<ReintentarMensajesFallidosHandler>();
        services.AddScoped<ListarAvisosHandler>();
        services.AddScoped<CrearSuscripcionHandler>();
        services.AddScoped<ListarSuscripcionesHandler>();

        services.AddScoped<ObtenerResumenEnviosHandler>();
        services.AddScoped<ObtenerMotivosNoEntregaHandler>();
        services.AddScoped<ObtenerActividadComercialHandler>();
        services.AddScoped<ObtenerResultadosRepartidoresHandler>();
        services.AddScoped<ObtenerCumplimientoHandler>();
        services.AddScoped<ObtenerDetalleLiquidacionHandler>();
        services.AddScoped<ObtenerPuntualidadHandler>();
        services.AddScoped<ConfigurarDireccionRecepcionHandler>();
        services.AddScoped<ObtenerDireccionRecepcionHandler>();
        return services;
    }
}
